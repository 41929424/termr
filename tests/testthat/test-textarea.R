ta_app <- function(value = "", width = 30, height = 8, ...) {
  ed <- text_area(value, id = "ed", ...)
  a <- app(ed)
  list(app = a, ed = ed, pilot = test_app(a, width, height))
}

test_that("typing, Enter, Backspace and Delete edit the text", {
  t <- ta_app("")
  t$pilot$type("hello")
  t$pilot$press("enter")
  t$pilot$type("world")
  expect_identical(t$ed$value, "hello\nworld")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(2L, 6L))
  t$pilot$press("backspace")
  expect_identical(t$ed$value, "hello\nworl")
  t$pilot$press("home", "backspace")
  expect_identical(t$ed$value, "helloworl")
  t$pilot$press("left", "left", "delete")
  expect_identical(t$ed$value, "heloworl")
  t$pilot$press("ctrl+home", "delete")
  expect_identical(t$ed$value, "eloworl")
  t$pilot$press("ctrl+end")
  expect_identical(t$ed$cursor_column, 8L)
})

test_that("the text is drawn with a border, line numbers and wrapping", {
  t <- ta_app("alpha beta gamma delta\nshort", width = 18, height = 6, line_numbers = TRUE)
  text <- t$pilot$screen_text()
  expect_match(text[[2]], "^\u2502 *1 alpha beta")
  expect_true(any(grepl("^\u2502 +gamma delta", text)))
  expect_true(any(grepl("^\u2502 *2 short", text)))
  # Wrapped rows never exceed the content width.
  expect_true(all(nchar(text) == 18))
})

test_that("cursor movement follows visual rows and keeps its column", {
  t <- ta_app("abcdef\nab\nabcdefgh", width = 20, height = 6)
  t$pilot$press("end", "down")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(2L, 3L))
  t$pilot$press("down")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(3L, 7L))
  t$pilot$press("up", "up")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(1L, 7L))
  # Left at the start of a line goes to the end of the previous one.
  t$pilot$press("down", "home", "left")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(1L, 7L))
  t$pilot$press("right")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(2L, 1L))
  # Up on the first line goes to its start; down on the last to its end.
  t$pilot$press("ctrl+home", "up")
  expect_identical(t$ed$cursor_column, 1L)
  t$pilot$press("ctrl+end", "down")
  expect_identical(c(t$ed$cursor_row, t$ed$cursor_column), c(3L, 9L))
})

