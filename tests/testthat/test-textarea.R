test_that("undo groups typing by word and restores the cursor", {
  t <- ta_app("", width = 30)
  t$pilot$type("hello world")
  expect_identical(t$ed$value, "hello world")
  t$pilot$press("ctrl+z")
  expect_identical(t$ed$value, "hello ")
  expect_identical(t$ed$cursor_column, 7L)
  t$pilot$press("ctrl+z")
  expect_identical(t$ed$value, "")
  t$pilot$press("ctrl+z")
  expect_identical(t$ed$value, "")
  t$pilot$press("ctrl+y", "ctrl+y")
  expect_identical(t$ed$value, "hello world")
