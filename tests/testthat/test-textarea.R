test_that("wrapping starts keep every grapheme exactly once", {
  set.seed(3)
  for (i in 1:50) {
    n <- sample(1:60, 1)
    chars <- sample(c("a", "b", " ", "\u4e2d"), n, replace = TRUE)
    widths <- ifelse(chars == "\u4e2d", 2L, 1L)
    w <- sample(3:12, 1)
    starts <- editor_wrap_starts(chars, widths, w)
    expect_identical(starts[[1]], 1L)
    expect_true(all(diff(starts) > 0L))
    ends <- c(starts[-1] - 1L, n)
    for (k in seq_along(starts)) {
      row_w <- sum(widths[starts[[k]]:ends[[k]]])
      # A row fits, except for a single wide character or one hanging space.
      expect_true(row_w <= w + 1L, info = paste(i, k))
    }
  }
})
