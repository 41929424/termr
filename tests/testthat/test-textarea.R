test_that("find: next, previous, wrap, case and regex", {
  t <- ta_app("Foo bar\nfoo baz\nxx FOO", width = 30)
  expect_true(t$ed$find("foo"))
  expect_identical(t$ed$selection, "Foo")
  t$ed$find_next()
  expect_identical(c(t$ed$cursor_row, t$ed$selection), c(2L, "foo"))
  t$ed$find_next()
  expect_identical(c(t$ed$cursor_row, t$ed$selection), c(3L, "FOO"))
  t$ed$find_next()
  expect_identical(c(t$ed$cursor_row, t$ed$selection), c(1L, "Foo"))
  t$ed$find_previous()
  expect_identical(c(t$ed$cursor_row, t$ed$selection), c(3L, "FOO"))
  expect_identical(t$ed$match_count, 3L)
  t$ed$find("foo", case_sensitive = TRUE)
  expect_identical(t$ed$match_count, 1L)
  expect_identical(t$ed$selection, "foo")
  expect_true(t$ed$find("b[a-z]+", regex = TRUE))
  expect_error(t$ed$find("(", regex = TRUE), "Invalid regular expression")
  expect_false(t$ed$find("nothing"))
})

test_that("the find bar edits the query incrementally", {
  t <- ta_app("alpha\nbeta\nalphabet", width = 30, height = 7)
  t$pilot$press("ctrl+f")
  expect_true(t$ed$find_open)
  t$pilot$type("alp")
  expect_identical(t$ed$selection, "alp")
  expect_identical(t$ed$match_count, 2L)
  expect_true(any(grepl("Find: alp_", t$pilot$screen_text())))
  t$pilot$press("enter")
  expect_identical(t$ed$cursor_row, 3L)
  t$pilot$press("backspace", "backspace", "backspace")
  t$pilot$type("zzz")
  expect_true(any(grepl("no matches", t$pilot$screen_text())))
  t$pilot$press("ctrl+r")
  t$pilot$press("backspace", "backspace", "backspace")
  t$pilot$type("(")
  expect_true(any(grepl("bad regex", t$pilot$screen_text())))
  t$pilot$press("escape")
  expect_false(t$ed$find_open)
  # Typing goes to the text again.
  t$pilot$type("Q")
  expect_match(t$ed$value, "Q")
})

