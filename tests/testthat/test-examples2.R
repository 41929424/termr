test_that("editor edits, undoes, searches and reports the position", {
  pilot <- test_app(load_example("editor"), 80, 24)
  pilot$step()
  ed <- pilot$query_one("#editor")
  expect_true(ed$focused)
  expect_match(pilot$query_one("#position")$text, "Ln 1, Col 1")
  pilot$type("Hi ")
  expect_identical(substr(ed$value, 1, 3), "Hi ")
  expect_match(pilot$query_one("#position")$text, "modified")
  pilot$press("ctrl+z")
  expect_false(identical(substr(ed$value, 1, 3), "Hi "))
  pilot$press("ctrl+f")
  pilot$type("filler")
  expect_match(ed$selection, "filler")
  pilot$press("escape")
  pilot$press("ctrl+g")
  expect_s3_class(pilot$app$screen, "ModalScreen")
  pilot$type("5")
  pilot$press("enter")
  expect_identical(ed$cursor_row, 5L)
  pilot$press("ctrl+q")
  expect_true(pilot$exited)
})

test_that("accessibility-demo cycles themes and works without colour", {
  pilot <- test_app(load_example("accessibility-demo"), 90, 30)
  expect_match(pilot$query_one("#theme")$text, "default")
  pilot$press("t")
  expect_identical(pilot$app$theme$name, "dark")
  pilot$press("t", "t")
  expect_identical(pilot$app$theme$name, "high-contrast")
  expect_match(pilot$query_one("#theme")$text, "high-contrast")
  pilot$press("m")
  expect_true(motion_reduced(pilot$app))
  mono <- test_app(load_example("accessibility-demo"), 90, 30, color_mode = "none")
  expect_match(paste(mono$screen_text(), collapse = "\n"), "Accessibility preview")
  mono$press("q")
  expect_true(mono$exited)
})
