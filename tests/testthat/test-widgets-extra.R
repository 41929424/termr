test_that("rules, sparklines, metrics and key/value lists render", {
  expect_identical(render_widget(rule(title = "Results"), 15, 1)$to_text(), "\u2500\u2500\u2500 Results \u2500\u2500\u2500")
  v <- render_widget(horizontal(label("a"), rule("vertical"), label("b"), style = style(height = 2)), 3, 2)
  expect_identical(v$to_text(), c("a\u2502b", " \u2502 "))
  s <- sparkline(c(0, 1, 2, 3, 4, 5, 6, 7, NA))
  expect_identical(render_widget(s, 9, 1)$to_text(), "\u2581\u2582\u2583\u2584\u2585\u2586\u2587\u2588 ")
  s$push(c(7, 0))
  expect_identical(length(s$data), 11L)
  expect_identical(sparkline_text(1:10, 4), sparkline_text(7:10, 4))
  expect_identical(nchar(sparkline_text(1:10, 4, summary = "mean")), 4L)
  expect_identical(sparkline_text(c(5, 5), 2), "\u2584\u2584")
  m <- metric("Accuracy", 0.943, delta = 0.012)
  text <- render_widget(m, 20, 4)$to_text()
  expect_match(text[[2]], "Accuracy")
  expect_match(text[[3]], "0.943 +\u25b2 0.012")
  m$update(0.9, delta = -0.043)
  expect_match(render_widget(m, 20, 4)$to_text()[[3]], "\u25bc 0.043")
  m2 <- metric("Rows", 1234567)
  expect_match(render_widget(m2, 20, 4)$to_text()[[3]], "1,234,567")
  kv <- key_value(list(Rows = 32, Source = "mtcars"))
  expect_identical(render_widget(kv, 16, 2)$to_text(), c("Rows    32      ", "Source  mtcars  "))
  expect_error(key_value(list(1, 2)), "named")
})

test_that("log views append, cap their size and follow the end", {
  logs <- log_view(max_lines = 5, id = "log")
  a <- app(logs)
  pilot <- test_app(a, 20, 3)
  for (i in 1:4) logs$write("line ", i)
  pilot$step()
  expect_identical(pilot$screen_text()[[3]], "line 4             \u2588")
  logs$write("bad\nworse", level = "error")
  pilot$step()
  expect_identical(logs$lines, c("line 2", "line 3", "line 4", "bad", "worse"))
  expect_identical(pilot$driver$terminal$screen$get_cell(1, 3)$fg, "bright_red")
  pilot$press("up", "up")
  expect_false(logs$at_end())
  logs$write("more")
  pilot$step()
  expect_false(any(grepl("more", pilot$screen_text())))
  pilot$press("end")
  logs$write("latest")
  pilot$step()
  expect_identical(substr(pilot$screen_text()[[3]], 1, 6), "latest")
  logs$pause()
  logs$write("hidden")
  pilot$step()
  expect_false(any(grepl("hidden", pilot$screen_text())))
  logs$resume()
  pilot$step()
  expect_match(pilot$screen_text()[[3]], "hidden")
  logs$clear()
  expect_length(logs$lines, 0)
  expect_error(logs$write("x", level = "fatal"), "level")
})
