test_that("progress bars render determinate and indeterminate states", {
  pb <- progress_bar(0.5)
  buf <- render_widget(pb, 15, 1)
  text <- buf$to_text()
  expect_match(text, " 50%$")
  expect_identical(substr(text, 1, 5), strrep("\u2501", 5))
  expect_identical(buf$get_cell(1, 1)$fg, "bright_cyan")
  expect_identical(buf$get_cell(6, 1)$fg, "bright_black")
  pb$advance(0.5)
  expect_identical(pb$value, 1)
  expect_identical(render_widget(pb, 15, 1)$get_cell(1, 1)$fg, "bright_green")
  busy <- progress_bar(NA)
  pilot <- test_app(app(busy), 20, 1)
  colours <- function() pilot$driver$terminal$screen$fg[1, ]
  first <- colours()
  pilot$advance(0.3)
  # The moving segment is the same character in another colour.
  expect_false(identical(first, colours()))
  expect_error(progress_bar(-1), "non-negative")
})

