test_that("checkbox toggles with keys and mouse and sends messages", {
  got <- logical()
  cb <- checkbox("Enable logs", id = "cb")
  a <- app(vertical(cb), on("checkbox.changed", function(event, app) got <<- c(got, event$data$value)))
  pilot <- test_app(a, 20, 2)
  expect_identical(pilot$screen_text()[[1]], "[ ] Enable logs     ")
  pilot$press("space")
  expect_true(cb$value)
  expect_match(pilot$screen_text()[[1]], "^\\[x\\]")
  pilot$click("#cb")
  pilot$press("enter")
  expect_identical(got, c(TRUE, FALSE, TRUE))
  expect_error(checkbox("x", value = "yes"), "TRUE or FALSE")
})

test_that("radio sets keep a single selection", {
  got <- character()
  rs <- radio_set(radio_button("CSV", "csv"), radio_button("JSON", "json", id = "json"), radio_button("XML", "xml"),
                  selected = "csv", id = "fmt")
  a <- app(vertical(rs), on("radio_set.changed", function(event, app) got <<- c(got, event$data$value)))
  pilot <- test_app(a, 20, 4)
  expect_identical(rs$value, "csv")
  dot <- "\u2022"
  expect_identical(substr(pilot$screen_text()[[1]], 1, 3), paste0("(", dot, ")"))
  pilot$press("down")
  expect_identical(rs$value, "json")
  expect_identical(a$focused$id, "json")
  pilot$press("down", "down")
  expect_identical(rs$value, "csv")
  pilot$click(3, 3)
  expect_identical(rs$value, "xml")
  expect_identical(sum(vapply(rs$children, function(b) b$selected, logical(1))), 1L)
  expect_identical(got, c("json", "xml", "csv", "xml"))
  expect_error(rs$value <- "nope", "No radio button")
  expect_error(radio_set(label("x")), "radio_button")
})

test_that("dropdown opens a list, selects and closes", {
  got <- NULL
  dd <- dropdown(c(Comma = "csv", JSON = "json", Parquet = "parquet"), id = "fmt")
  a <- app(vertical(dd, label("below", id = "below")), on("dropdown.changed", function(event, app) got <<- event$data))
  pilot <- test_app(a, 30, 12)
  expect_match(pilot$screen_text()[[2]], "Select")
  pilot$press("enter")
  expect_true(inherits(a$screen, "DropdownScreen"))
  text <- pilot$screen_text()
  expect_match(text[[5]], "Comma")
  expect_match(text[[6]], "JSON")
  pilot$press("down", "enter")
  expect_false(inherits(a$screen, "DropdownScreen"))
  expect_identical(dd$value, "json")
  expect_identical(got, list(value = "json", label = "JSON"))
  expect_match(pilot$screen_text()[[2]], "JSON")
  expect_identical(a$focused$id, "fmt")
  # Escape and clicking outside close without changing the value.
  pilot$press("enter", "escape")
  expect_identical(dd$value, "json")
  pilot$click("#fmt")
  pilot$click(29, 11)
  expect_false(inherits(a$screen, "DropdownScreen"))
  # Mouse selection.
  pilot$click("#fmt")
  pilot$click(5, 7)
  expect_identical(dd$value, "parquet")
  expect_error(dd$value <- "xls", "not one of the choices")
})

